// Inlines zig-out/bin/core.wasm into src/core-bytes.js (TRD 2, "Size budget":
// encoding lever), so there is no .wasm file to serve or fetch. The bytes are
// a Latin-1 string literal rather than base64: served as UTF-8 it gzips about
// 15% smaller (measured 2026-10-24: 19.1 KB vs 22.4 KB for a 49 KB core).
//
//   node scripts/embed-wasm.js        run by `npm run build:wasm`

import {readFileSync, writeFileSync} from "node:fs";

const wasm = readFileSync(new URL("../zig-out/bin/core.wasm", import.meta.url));
let s = "";
for (const b of wasm) {
  if (b === 0x5c) s += "\\\\";
  else if (b === 0x22) s += "\\\"";
  else if (b === 0x0a) s += "\\n";
  else if (b === 0x0d) s += "\\r";
  else if (b < 0x20 || b === 0x7f) s += "\\x" + b.toString(16).padStart(2, "0");
  else s += String.fromCharCode(b);
}
writeFileSync(new URL("../src/core-bytes.js", import.meta.url), `// Generated by scripts/embed-wasm.js from zig-out/bin/core.wasm; do not edit.
// A Latin-1 string: each character's code is one byte of the module.
const s = "${s}";
export default Uint8Array.from(s, (c) => c.charCodeAt(0));
`);
console.log(`core.wasm ${wasm.length} B -> src/core-bytes.js`);
