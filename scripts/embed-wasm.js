// Inlines zig-out/bin/core.wasm into src/core-bytes.js (TRD 2, "Size budget":
// encoding lever), so there is no .wasm file to serve or fetch. The module is
// deflated (zlib format) and base64-encoded; core.js inflates it with the
// built-in DecompressionStream. Deflate removes the redundancy gzip would
// otherwise have to find through an escaped string, so this gzips about 16%
// smaller than the Latin-1 string literal it replaces (measured 2026-10-24 on
// the 59 KB M3 core: 22.9 KB vs 27.4 KB).
//
// The threaded core is not embedded: it is copied to src/core-mt.wasm and
// fetched only where threads run (TRD 3, Build, packaging and deployment).
//
//   node scripts/embed-wasm.js        run by `npm run build:wasm`

import {copyFileSync, readFileSync, writeFileSync} from "node:fs";
import {deflateSync} from "node:zlib";

const wasm = readFileSync(new URL("../zig-out/bin/core.wasm", import.meta.url));
const packed = deflateSync(wasm, {level: 9}).toString("base64");
writeFileSync(new URL("../src/core-bytes.js", import.meta.url), `// Generated by scripts/embed-wasm.js from zig-out/bin/core.wasm; do not edit.
// The module, deflated (zlib format) and base64-encoded.
export default "${packed}";
`);
console.log(`core.wasm ${wasm.length} B (${packed.length} B packed) -> src/core-bytes.js`);
copyFileSync(new URL("../zig-out/bin/core-mt.wasm", import.meta.url), new URL("../src/core-mt.wasm", import.meta.url));
console.log(`core-mt.wasm ${readFileSync(new URL("../src/core-mt.wasm", import.meta.url)).length} B -> src/core-mt.wasm`);
